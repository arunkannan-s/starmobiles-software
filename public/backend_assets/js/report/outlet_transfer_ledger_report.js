$(async function () {
    "use strict";
    /** #################### -- The base JS part should be on top of all JS files --  #################### **/
    let base_url = $('#base_url').val();
    let language_name = $('#language_name').val();
    let language_path = '/resources/lang/' + language_name + '.json';
    let language_file = base_url + language_path;
    let language_key = {};

    async function loadLanguage() {
      try {
        const res = await fetch(language_file);
        language_key = await res.json();
      } catch (err) {
        console.error('Failed to load language file:', err);
      }
    }
    await loadLanguage();

    let company_data = $('#company_data').val();
    let company_session_data = {};
    try {
        company_session_data = JSON.parse(company_data);
    } catch (e) {
        console.error('Error parsing company info:', e);
    }
    /** #################### -- The base JS part should be on top of all JS files --  #################### **/

    let outletId = '';
    let dateFrom = '';
    let dateTo = '';
    let type = 'All';
    let table;
    let summaryData = {};

    let ledgerReportRoute;
    try {
        ledgerReportRoute = route('report.outlet-transfer-ledger-report', {}, false, Ziggy);
    } catch (e) {
        ledgerReportRoute = '/reports/outlet-transfer-ledger-report';
    }

    let currentFilterInfo = {
        outlet: null,
        date_from: null,
        date_to: null,
        type: 'All',
        generated_at: null,
        generated_by: null
    };

    function updateFilteredInformation(filterInfo) {
        if (!filterInfo) {
            $('#filteredInformation').hide();
            return;
        }
        let html = '<p class="pb-0 mb-0"><strong>' + (language_key.OutletTransferLedgerReport || 'Outlet Transfer Ledger Report') + '</strong></p>';

        if (filterInfo.outlet) {
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.OutletName || 'Outlet Name') + ': </strong> ' + (filterInfo.outlet.name || '-') + '</p>';
            if (filterInfo.outlet.phone) {
                html += '<p class="pb-0 mb-0"><strong>' + (language_key.OutletPhone || 'Outlet Phone') + ': </strong> ' + filterInfo.outlet.phone + '</p>';
            }
            if (filterInfo.outlet.address) {
                html += '<p class="pb-0 mb-0"><strong>' + (language_key.OutletAddress || 'Outlet Address') + ': </strong> ' + filterInfo.outlet.address + '</p>';
            }
        }

        if (filterInfo.date_from || filterInfo.date_to) {
            let dateRange = (filterInfo.date_from || '') + ' to ' + (filterInfo.date_to || '');
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.DateRange || 'Date Range') + ': </strong> ' + dateRange + '</p>';
        }

        if (filterInfo.type && filterInfo.type !== 'All') {
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.Type || 'Type') + ': </strong> ' + filterInfo.type + '</p>';
        }

        if (filterInfo.generated_at) {
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.GeneratedOn || 'Generated on') + ': </strong> ' + filterInfo.generated_at + '</p>';
        }
        if (filterInfo.generated_by && (filterInfo.generated_by.name || filterInfo.generated_by.phone)) {
            let byText = [filterInfo.generated_by.name, filterInfo.generated_by.phone].filter(Boolean).join(', ');
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.GeneratedBy || 'Generated by') + ': </strong> ' + byText + '</p>';
        }

        $('#filterInfoContent').html(html);
        $('#filteredInformation').show();
    }

    function getExportHeader() {
        let header = '<div style="margin-bottom: 20px;">';
        header += '<h3 style="text-align: center; margin-bottom: 15px;">' + (language_key.OutletTransferLedgerReport || 'Outlet Transfer Ledger Report') + '</h3>';

        if (currentFilterInfo.outlet) {
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.OutletName || 'Outlet Name') + ': </strong> ' + (currentFilterInfo.outlet.name || '-') + '</p>';
            if (currentFilterInfo.outlet.phone) {
                header += '<p style="margin: 5px 0;"><strong>' + (language_key.OutletPhone || 'Outlet Phone') + ': </strong> ' + currentFilterInfo.outlet.phone + '</p>';
            }
            if (currentFilterInfo.outlet.address) {
                header += '<p style="margin: 5px 0;"><strong>' + (language_key.OutletAddress || 'Outlet Address') + ': </strong> ' + currentFilterInfo.outlet.address + '</p>';
            }
        }

        if (currentFilterInfo.date_from || currentFilterInfo.date_to) {
            let dateRange = (currentFilterInfo.date_from || '') + ' to ' + (currentFilterInfo.date_to || '');
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.DateRange || 'Date Range') + ': </strong> ' + dateRange + '</p>';
        }
        if (currentFilterInfo.type && currentFilterInfo.type !== 'All') {
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.Type || 'Type') + ': </strong> ' + currentFilterInfo.type + '</p>';
        }
        if (currentFilterInfo.generated_at) {
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.GeneratedOn || 'Generated on') + ': </strong> ' + currentFilterInfo.generated_at + '</p>';
        }
        if (currentFilterInfo.generated_by && (currentFilterInfo.generated_by.name || currentFilterInfo.generated_by.phone)) {
            let byText = [currentFilterInfo.generated_by.name, currentFilterInfo.generated_by.phone].filter(Boolean).join(', ');
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.GeneratedBy || 'Generated by') + ': </strong> ' + byText + '</p>';
        }

        header += '</div>';
        return header;
    }

    function updateFooterTotals(summary) {
        if (summary) {
            $('#totalDebit').text(summary.total_debit || '0.00');
            $('#totalCredit').text(summary.total_credit || '0.00');
            $('#openingBalance').text(summary.opening_balance || '0.00');
            $('#closingBalance').text(summary.closing_balance || '0.00');
        }
    }

    if (typeof pdfMake !== 'undefined') {
        try {
            if (typeof pdfMake.vfs === 'undefined' || Object.keys(pdfMake.vfs).length === 0) {
                pdfMake.fonts = {
                    Roboto: {
                        normal: 'Roboto-Regular.ttf',
                        bold: 'Roboto-Medium.ttf',
                        italics: 'Roboto-Italic.ttf',
                        bolditalics: 'Roboto-MediumItalic.ttf'
                    }
                };
            }
        } catch (e) {
            console.warn('PDF fonts configuration warning:', e);
        }
    }

    function initTable() {
        if ($.fn.DataTable.isDataTable('#outletTransferLedgerReportTable')) {
            $('#outletTransferLedgerReportTable').DataTable().destroy();
        }

        table = $('#outletTransferLedgerReportTable').DataTable({
            processing: true,
            serverSide: false,
            paging: false,
            searching: true,
            ordering: true,
            info: true,
            autoWidth: false,
            responsive: true,
            data: [],
            columns: [
                { data: 'sn' },
                { data: 'date_time' },
                { data: 'transaction_type' },
                { data: 'transaction_no' },
                { data: 'debit' },
                { data: 'credit' },
                { data: 'outlet' }
            ],
            order: [[0, 'asc']],
            dom: '<"card-header border-bottom p-3"<"head-label"><"dt-action-buttons text-end"B>>' +
                '<"row"<"col-sm-12"tr>>',
            buttons: [
                {
                    extend: 'collection',
                    className: 'btn btn-primary dropdown-toggle me-2',
                    text: '<i class="ti tabler-file-export me-sm-1"></i> <span class="d-none d-sm-inline-block">'+language_key['Export']+'</span>',
                    buttons: [
                        {
                            extend: 'print',
                            text: '<i class="ti tabler-printer me-1"></i>' + (language_key.Print || 'Print'),
                            className: 'dropdown-item',
                            title: '',
                            customize: function (win) {
                                $(win.document.body).prepend(getExportHeader());
                            }
                        },
                        {
                            extend: 'excelHtml5',
                            text: '<i class="ti tabler-file-spreadsheet me-1"></i>' + (language_key.Excel || 'Excel'),
                            className: 'dropdown-item',
                            title: '',
                            customize: function (xlsx) {
                                var sheet = xlsx.xl.worksheets['sheet1.xml'];
                                $('row c[r^="A"]', sheet).attr('s', '2');
                            },
                            messageTop: function() {
                                let header = (language_key.OutletTransferLedgerReport || 'Outlet Transfer Ledger Report') + '\n\n';
                                if (currentFilterInfo.outlet) {
                                    header += (language_key.OutletName || 'Outlet Name') + ': ' + (currentFilterInfo.outlet.name || '-') + '\n';
                                }
                                if (currentFilterInfo.date_from || currentFilterInfo.date_to) {
                                    let dateRange = (currentFilterInfo.date_from || '') + ' to ' + (currentFilterInfo.date_to || '');
                                    header += (language_key.DateRange || 'Date Range') + ': ' + dateRange + '\n';
                                }
                                if (currentFilterInfo.type && currentFilterInfo.type !== 'All') {
                                    header += (language_key.Type || 'Type') + ': ' + currentFilterInfo.type + '\n';
                                }
                                if (currentFilterInfo.generated_at) {
                                    header += (language_key.GeneratedOn || 'Generated on') + ': ' + currentFilterInfo.generated_at + '\n';
                                }
                                return header;
                            }
                        },
                        {
                            extend: 'pdf',
                            text: '<i class="ti tabler-file-description me-1"></i>' + (language_key.Pdf || 'PDF'),
                            className: 'dropdown-item',
                            title: '',
                            orientation: 'portrait',
                            pageSize: 'A4',
                            messageTop: function() {
                                let header = (language_key.OutletTransferLedgerReport || 'Outlet Transfer Ledger Report') + '\n\n';
                                if (currentFilterInfo.outlet) {
                                    header += (language_key.OutletName || 'Outlet Name') + ': ' + (currentFilterInfo.outlet.name || '-') + '\n';
                                }
                                if (currentFilterInfo.date_from || currentFilterInfo.date_to) {
                                    let dateRange = (currentFilterInfo.date_from || '') + ' to ' + (currentFilterInfo.date_to || '');
                                    header += (language_key.DateRange || 'Date Range') + ': ' + dateRange + '\n';
                                }
                                if (currentFilterInfo.type && currentFilterInfo.type !== 'All') {
                                    header += (language_key.Type || 'Type') + ': ' + currentFilterInfo.type + '\n';
                                }
                                if (currentFilterInfo.generated_at) {
                                    header += (language_key.GeneratedOn || 'Generated on') + ': ' + currentFilterInfo.generated_at + '\n';
                                }
                                return header;
                            }
                        }
                    ]
                },
                {
                    text: '<i class="ti tabler-filter me-sm-1"></i> <span class="d-none d-sm-inline-block">'+language_key['Filter']+'</span>',
                    className: 'btn create-new btn-primary',
                    action: function (e, dt, node, config) {
                        $('#filterSection').slideToggle();
                    }
                }
            ],

            drawCallback: function(settings) {
                if (summaryData) {
                    updateFooterTotals(summaryData);
                }
            }
        });
    }

    function initSelect2() {
        if ($('#outlet_id').length && !$('#outlet_id').hasClass('select2-hidden-accessible')) {
            $('#outlet_id').select2({
                dropdownParent: $('#filterSection'),
                width: '100%',
                placeholder: language_key.SelectOutlet || 'Select Outlet',
                allowClear: true
            });
        }

        if ($('#type').length && !$('#type').hasClass('select2-hidden-accessible')) {
            $('#type').select2({
                dropdownParent: $('#filterSection'),
                width: '100%',
                placeholder: language_key.Type || 'Type',
                allowClear: false
            });
        }
    }

    function loadReportData() {
        if (!outletId) {
            Swal.fire({
                icon: 'warning',
                title: language_key.Warning || 'Warning',
                text: language_key.PleaseSelectOutlet || 'Please select an outlet',
                confirmButtonText: language_key.OK || 'OK'
            });
            return;
        }

        $.ajax({
            url: base_url + ledgerReportRoute,
            type: 'GET',
            headers: {
                'X-Requested-With': 'XMLHttpRequest',
                'Accept': 'application/json'
            },
            data: {
                outlet_id: outletId,
                date_from: dateFrom,
                date_to: dateTo,
                type: type
            },
            success: function(response) {
                if (response.success && response.data && response.data.transactions) {
                    summaryData = response.data.summary || {};

                    if (response.data.filter_info) {
                        currentFilterInfo = response.data.filter_info;
                        currentFilterInfo.type = type || currentFilterInfo.type || 'All';
                        updateFilteredInformation(currentFilterInfo);
                    } else {
                        currentFilterInfo = {
                            outlet: null,
                            date_from: null,
                            date_to: null,
                            type: type,
                            generated_at: null,
                            generated_by: null
                        };
                        updateFilteredInformation(currentFilterInfo);
                    }

                    table.clear();
                    table.rows.add(response.data.transactions);
                    table.draw();

                    updateFooterTotals(summaryData);
                } else {
                    table.clear().draw();
                    $('#filteredInformation').hide();
                    updateFooterTotals({
                        total_debit: '0.00',
                        total_credit: '0.00',
                        opening_balance: '0.00',
                        closing_balance: '0.00'
                    });
                }
            },
            error: function(xhr) {
                let errorMessage = language_key.ErrorLoadingData || 'Error loading data';
                if (xhr.responseJSON && xhr.responseJSON.message) {
                    errorMessage = xhr.responseJSON.message;
                }
                Swal.fire({
                    icon: 'error',
                    title: language_key.Error || 'Error',
                    text: errorMessage,
                    confirmButtonText: language_key.OK || 'OK'
                });
            }
        });
    }

    $(document).on('submit', '#filterForm', function(e) {
        e.preventDefault();
        e.stopPropagation();
        return false;
    });

    $(document).on('keydown', '#filterForm input, #filterForm select', function(e) {
        if (e.key === 'Enter' || e.keyCode === 13) {
            e.preventDefault();
            e.stopPropagation();
            $('#applyFilter').click();
            return false;
        }
    });

    $(document).on('click', '#applyFilter', function(e) {
        e.preventDefault();
        e.stopPropagation();
        outletId = $('#outlet_id').val();
        dateFrom = $('#date_from').val();
        dateTo = $('#date_to').val();
        type = $('#type').val() || 'All';
        loadReportData();
        return false;
    });

    function checkAndShowFilters() {
        let dateFromVal = $('#date_from').val();
        let dateToVal = $('#date_to').val();
        let outletIdVal = $('#outlet_id').val();
        let typeVal = $('#type').val() || 'All';

        if (dateFromVal || dateToVal || outletIdVal) {
            outletId = outletIdVal || '';
            dateFrom = dateFromVal || '';
            dateTo = dateToVal || '';
            type = typeVal;

            $('#filterSection').show();
            initSelect2();
            if (outletId) {
                loadReportData();
            }
        }
    }

    $('#filterSection').on('shown.bs.collapse shown', function () {
        initSelect2();
    });

    initTable();
    initSelect2();
    checkAndShowFilters();
});
